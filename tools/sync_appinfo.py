#!/usr/bin/env python3
"""
Mirrors the single source of identity into the non-code artefacts.

    python tools/sync_appinfo.py             # rewrite installer/appinfo.ini + docs/appinfo.json
    python tools/sync_appinfo.py --check     # CI mode: exit 1 when the mirrors are stale

It reads every ``public const string`` in
``src/VoidRemove.Shared/AppInfo.cs`` (including verbatim literals and ``+`` concatenations
of other constants) plus the ``<VersionPrefix>`` from ``Directory.Build.props``, and writes
them to:

  installer/appinfo.ini     read by the Inno Setup script (setup.iss) via ReadIni
  docs/appinfo.json         read by the MkDocs site

So renaming the product or bumping the version touches exactly two places.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
APPINFO_CS = REPO_ROOT / "src" / "VoidRemove.Shared" / "AppInfo.cs"
BUILD_PROPS = REPO_ROOT / "Directory.Build.props"
INI_PATH = REPO_ROOT / "installer" / "appinfo.ini"
JSON_PATH = REPO_ROOT / "docs" / "appinfo.json"

DECLARATION = re.compile(r"public\s+const\s+string\s+(\w+)\s*=\s*([^;]+);")
VERSION_PREFIX = re.compile(r"<VersionPrefix>([^<]+)</VersionPrefix>")

ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "0": "\0"}


def _unescape(text: str) -> str:
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == "\\" and i + 1 < len(text):
            out.append(ESCAPES.get(text[i + 1], text[i + 1]))
            i += 2
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def _split_terms(expr: str) -> list[tuple[str, str]]:
    terms: list[tuple[str, str]] = []
    current = ""
    buffer = ""
    in_string = False
    verbatim = False
    i = 0
    n = len(expr)

    while i < n:
        ch = expr[i]
        if in_string:
            if verbatim:
                if ch == '"':
                    if i + 1 < n and expr[i + 1] == '"':
                        buffer += '"'
                        i += 2
                        continue
                    in_string = False
                    terms.append(("str", buffer))
                    buffer = ""
                    i += 1
                    continue
                buffer += ch
                i += 1
            else:
                if ch == "\\" and i + 1 < n:
                    buffer += expr[i:i + 2]
                    i += 2
                    continue
                if ch == '"':
                    in_string = False
                    terms.append(("str", _unescape(buffer)))
                    buffer = ""
                    i += 1
                    continue
                buffer += ch
                i += 1
        else:
            if ch == "@":
                if i + 1 < n and expr[i + 1] == '"':
                    in_string = True
                    verbatim = True
                    i += 2
                    continue
                current += ch
                i += 1
            elif ch == '"':
                in_string = True
                verbatim = False
                i += 1
            elif ch == "+":
                if current.strip():
                    terms.append(("id", current.strip()))
                current = ""
                i += 1
            else:
                current += ch
                i += 1

    if current.strip():
        terms.append(("id", current.strip()))
    return terms


def parse_constants(source: str) -> dict[str, str]:
    constants: dict[str, str] = {}
    for match in DECLARATION.finditer(source):
        name, expression = match.group(1), match.group(2)
        value_parts = []
        for kind, raw in _split_terms(expression):
            if kind == "str":
                value_parts.append(raw)
            else:
                if raw not in constants:
                    raise ValueError(f"AppInfo constant '{name}' references unknown '{raw}'")
                value_parts.append(constants[raw])
        constants[name] = "".join(value_parts)
    return constants


def read_version() -> str:
    match = VERSION_PREFIX.search(BUILD_PROPS.read_text(encoding="utf-8"))
    if not match:
        raise ValueError("<VersionPrefix> not found in Directory.Build.props")
    return match.group(1).strip()


def build_ini(constants: dict[str, str], version: str) -> str:
    lines = ["; Generated by tools/sync_appinfo.py - do not edit by hand.", ""]
    lines.append("[App]")
    for name, value in constants.items():
        lines.append(f"{name}={value}")
    lines.append("")
    lines.append("[Version]")
    lines.append(f"VersionPrefix={version}")
    lines.append("")
    # LF on purpose so the byte-for-byte freshness check is stable across git checkouts.
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the mirrors are stale")
    args = parser.parse_args()

    constants = parse_constants(APPINFO_CS.read_text(encoding="utf-8"))
    version = read_version()

    ini_bytes = b"\xef\xbb\xbf" + build_ini(constants, version).encode("utf-8")
    json_bytes = (
        json.dumps({"version": version, "constants": constants}, ensure_ascii=False, indent=2) + "\n"
    ).encode("utf-8")

    if args.check:
        stale = False
        for path, expected in ((INI_PATH, ini_bytes), (JSON_PATH, json_bytes)):
            if not path.exists() or path.read_bytes() != expected:
                print(f"stale: {path}")
                stale = True
        if stale:
            print("run: python tools/sync_appinfo.py")
            return 1
        print(f"up to date: {len(constants)} constants")
        return 0

    INI_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    INI_PATH.write_bytes(ini_bytes)
    JSON_PATH.write_bytes(json_bytes)
    print(f"wrote {INI_PATH} and {JSON_PATH} ({len(constants)} constants, version {version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
